    }
}

[Serializable]
public class StoryTransitionDocument
{
    public string type = "none";
    public float duration = .35f;

    public string normalizedType
    {
        get
        {
            string value = (type ?? string.Empty).Trim().ToLowerInvariant();
            switch (value)
            {
                case "inherit":
                case "fade":
                case "crossfade":
                case "wipeleft":
                case "wiperight":
                case "wipeup":
                case "wipedown":
                case "pushleft":
                case "pushright":
                case "pushup":
                case "pushdown":
                case "zoomcross":
                case "radial":
                    return value;
                default:
                    return "none";
            }
        }
    }

    public float normalizedDuration => Math.Max(.1f, Math.Min(2f, duration <= 0f ? .35f : duration));
}

