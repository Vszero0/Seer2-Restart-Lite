[Serializable]
public class StoryNodeDocument
{
    public string id;
    public string displayName;
    public string flowRole = "sequence";
    public string fallbackNodeId;
    public StoryMapReferenceDocument[] mapReferences;
    public StoryActorReferenceDocument[] actorReferences;
    public StorySceneDocument[] scenes;
    public StoryTextStyleDocument style;
    public StoryCommandDocument[] commands;
    public StoryNodeTransitionDocument[] transitions;

    public string normalizedFlowRole => string.Equals(flowRole, "branch", StringComparison.OrdinalIgnoreCase)
        ? "branch"
        : "sequence";
    public bool isBranch => string.Equals(normalizedFlowRole, "branch", StringComparison.OrdinalIgnoreCase);
    public bool defaultEnds
    {
        get
        {
            StoryNodeTransitionDocument defaultTransition = (transitions ?? Array.Empty<StoryNodeTransitionDocument>())
                .FirstOrDefault(transition => transition != null && transition.isDefault);
            if (defaultTransition != null)
                return defaultTransition.isEnd;

            return isBranch && string.IsNullOrWhiteSpace(fallbackNodeId);
        }
    }
    public bool hasEndingPath => defaultEnds
        || (transitions ?? Array.Empty<StoryNodeTransitionDocument>()).Any(transition => transition != null && transition.isEnd)
        || (commands ?? Array.Empty<StoryCommandDocument>()).Any(command => command != null
            && string.Equals(command.type, "end", StringComparison.OrdinalIgnoreCase)
            && (command.condition == null || !command.condition.hasConditions));
    public bool isEnding
    {
        get
        {
            bool hasUnconditionalEndCommand = (commands ?? Array.Empty<StoryCommandDocument>())
                .Any(command => command != null
                    && string.Equals(command.type, "end", StringComparison.OrdinalIgnoreCase)
                    && (command.condition == null || !command.condition.hasConditions));
            bool hasNodeTransition = (transitions ?? Array.Empty<StoryNodeTransitionDocument>())
                .Any(transition => transition != null && !transition.isEnd);
            bool hasCommandJump = (commands ?? Array.Empty<StoryCommandDocument>())
                .Any(command => command != null
                    && string.Equals(command.type, "jump", StringComparison.OrdinalIgnoreCase)
                    && !string.IsNullOrWhiteSpace(command.target));
            bool hasChoiceTarget = (commands ?? Array.Empty<StoryCommandDocument>())
                .SelectMany(command => command?.choices ?? Array.Empty<StoryChoiceDocument>())
                .Any(choice => choice != null && !string.IsNullOrWhiteSpace(choice.target));
            return (defaultEnds || hasUnconditionalEndCommand)
                && !hasNodeTransition
                && !hasCommandJump
                && !hasChoiceTarget;
        }
    }

    public StorySceneDocument GetScene(string sceneId)
    {
        if (string.IsNullOrWhiteSpace(sceneId) || scenes == null)
            return null;

        return scenes.FirstOrDefault(x => x != null && string.Equals(x.id, sceneId, StringComparison.OrdinalIgnoreCase));
    }
}

[Serializable]
public class StoryCommandDocument
{
    public string commandId;
    public string type;
    public string choiceOriginalType;
    public string choiceId;
    public string sceneId;
    public int mapId;
    public string bgmResourcePath;
    public string bg;
    public StoryTransitionDocument transition;
    public string actor;
    public string expression;
    public string text;
    public string target;
    public string args;
    public StoryLayoutDocument layout;
    public float actorSpacing;
    public float actorHeight;
    public float actorBottom;
    public float centerGap;
    public float stackOffset;
    public StoryChoiceDocument[] choices;
    public ConditionGroupDocument condition;
    public ConditionGroupDocument displayCondition;

    public StoryCommand ToCommand(StoryDocument document, StoryNodeDocument node = null)
    {
        string commandType = (type ?? string.Empty).Trim().ToLower();
        StoryCommand command = new StoryCommand();
        command.commandId = commandId;
        command.choiceId = choiceId;
        command.condition = condition;
        command.displayCondition = displayCondition;
        switch (commandType)
        {
            case "scene":
                command.type = StoryCommandType.Scene;
                StorySceneDocument scene = node?.GetScene(sceneId);
                StorySceneResourceDocument sceneResource = document?.GetSceneResource(scene?.sceneResourceId);
                command.mapId = sceneResource != null
                    ? 0
                    : scene != null && scene.mapId != 0 ? scene.mapId : mapId;
                command.bgmResourcePath = !string.IsNullOrEmpty(scene?.bgmResourcePath)
                    ? scene.bgmResourcePath
                    : !string.IsNullOrEmpty(sceneResource?.defaultBgmResourcePath)
                        ? sceneResource.defaultBgmResourcePath
                        : bgmResourcePath;
                command.args = !string.IsNullOrEmpty(sceneResource?.backgroundResourcePath)
                    ? sceneResource.backgroundResourcePath
                    : string.IsNullOrEmpty(bg)
                        ? (command.mapId != 0 ? "Maps/bg/" + command.mapId : args)
                        : bg;
                command.layout = scene?.layout ?? GetSceneLayout();
                command.actorLayouts = scene?.actors;
                command.transition = scene?.transition ?? transition;
                command.sceneActors = (scene?.actors ?? Array.Empty<StorySceneActorLayoutDocument>())
                    .Where(layout => layout != null && !string.IsNullOrWhiteSpace(layout.actorId))
                    .Select(layout => document?.GetActor(layout.actorId))
                    .Where(actorDocument => actorDocument != null)
                    .ToArray();
                return command;
            case "show":
                command.type = StoryCommandType.Show;
                command.actorId = actor;
                command.actorInfo = document?.GetActor(actor);
                command.args = GetActorShowArgs(document);
                return command.actorInfo == null && string.IsNullOrEmpty(command.args) ? null : command;
            case "hide":
                command.type = StoryCommandType.Hide;
                command.actorId = actor;
                command.args = string.IsNullOrEmpty(actor) ? args : actor;
                return command;
            case "say":
                command.type = StoryCommandType.Say;
                command.actorId = actor;
                command.actorInfo = document?.GetActor(actor);
                command.speaker = GetActorName(document);
                command.expression = expression;
                command.text = text;
                return command;
            case "narrate":
                command.type = StoryCommandType.Narrate;
                command.text = text;
                return command;
            case "choice":
                command.type = StoryCommandType.Choice;
                command.actorId = actor;
                command.actorInfo = document?.GetActor(actor);
                command.speaker = GetActorName(document);
                command.expression = expression;
                command.text = text;
                command.choices = (choices ?? Array.Empty<StoryChoiceDocument>())
                    .Select(x => x?.ToChoice())
                    .Where(x => x != null)
                    .ToList();
                return command;
            case "jump":
                command.type = StoryCommandType.Jump;
                command.args = target;
                return command;
            case "mission":
                command.type = StoryCommandType.Mission;
                command.args = args;
                return command;
            case "teleport":
                command.type = StoryCommandType.Teleport;
                command.args = args;
                return command;
            case "end":
                command.type = StoryCommandType.End;
                return command;
            default:
                return null;
        }
    }

    private string GetActorName(StoryDocument document)
    {
        StoryActorDocument actorDocument = document?.GetActor(actor);
        return actorDocument == null ? actor : actorDocument.displayName;
    }

    private string GetActorShowArgs(StoryDocument document)
    {
        StoryActorDocument actorDocument = document?.GetActor(actor);
        if (actorDocument == null)
            return args;

        string sprite = actorDocument.displaySprite;
        return string.IsNullOrEmpty(sprite) ? string.Empty : actorDocument.displayName + " " + sprite;
    }

    private StoryLayoutDocument GetSceneLayout()
    {
        if (layout != null)
            return layout;

        if (actorSpacing <= 0f && actorHeight <= 0f && actorBottom <= 0f && centerGap <= 0f && stackOffset <= 0f)
            return null;

        return new StoryLayoutDocument
        {
            actorSpacing = actorSpacing,
            actorHeight = actorHeight,
            actorBottom = actorBottom,
            centerGap = centerGap,
            stackOffset = stackOffset,
        };
    }
}

