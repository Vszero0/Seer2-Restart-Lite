[Serializable]
public class StoryDocument
{
    public int schemaVersion = 9;
    public string status = "published";
    public string id;
    public string title;
    public string summary;
    public string entry = "start";
    public StoryLayoutDocument layout;
    public StoryTextStyleDocument style;
    public StoryMissionDocument mission;
    public bool replayable = true;
    public StoryResourceDefinition[] resourceDefinitions;
    public StorySceneResourceDocument[] sceneResources;
    public StoryActorDocument[] actors;
    public StoryNodeDocument[] nodes;

    public bool isDraft => string.Equals(status, "draft", StringComparison.OrdinalIgnoreCase);
    public string normalizedStatus => isDraft ? "draft" : "published";
    public bool HasSupportedStatus => string.IsNullOrWhiteSpace(status)
        || isDraft
        || string.Equals(status, "published", StringComparison.OrdinalIgnoreCase);
    public bool IsValid => StoryValidator.Validate(this, out _);

    public MissionInfo ToMissionInfo()
    {
        if (isDraft || !IsValid)
            return null;

        return new MissionInfo
        {
            id = mission.id,
            typeId = (int)MissionType.Mod,
            replayable = replayable && mission.replayable,
            autoCompleteStory = true,
            title = string.IsNullOrEmpty(title) ? mission.title : title,
            checkpoints = new List<MissionCheckpoint>
            {
                new MissionCheckpoint
                {
                    id = "default",
                    mapId = mission.mapId,
                    storyId = "mod:" + id,
                    intro = string.IsNullOrEmpty(summary) ? mission.summary : summary,
                }
            },
            rewards = new List<Item>(),
        };
    }

    public StoryScript ToScript()
    {
        StoryScript script = new StoryScript
        {
            layout = layout,
            textStyle = style
        };
        foreach (StoryResourceDefinition resource in resourceDefinitions ?? Array.Empty<StoryResourceDefinition>())
        {
            if (resource == null || string.IsNullOrWhiteSpace(resource.path))
                continue;

            script.resourceSources[resource.path] = string.IsNullOrWhiteSpace(resource.source)
                ? "auto"
                : resource.source.Trim().ToLower();
        }
        if (nodes == null)
            return script;

        List<StoryNodeDocument> orderedNodes = GetOrderedNodes();
        List<StoryNodeDocument> sequenceNodes = orderedNodes
            .Where(node => node != null && !node.isBranch)
            .ToList();

        foreach (StoryNodeDocument node in orderedNodes)
        {
            if (node == null || string.IsNullOrEmpty(node.id))
                continue;

            script.labels[node.id] = script.commands.Count;
            bool isSceneOpening = false;
            StoryCommandDocument[] nodeCommands = node.commands ?? Array.Empty<StoryCommandDocument>();
            for (int commandIndex = 0; commandIndex < nodeCommands.Length; commandIndex++)
            {
                StoryCommand parsed = nodeCommands[commandIndex]?.ToCommand(this, node);
                if (parsed != null)
                {
                    parsed.pointId = node.id;
                    if (parsed.type == StoryCommandType.Scene)
                    {
                        isSceneOpening = true;
                    }
                    else if (parsed.type == StoryCommandType.Show && isSceneOpening)
                    {
                        // 场景命令已按场景角色表完成首次显示；跳过旧草稿自动生成的冗余 show。
                        continue;
                    }
                    else
                    {
                        isSceneOpening = false;
                    }

                    if (string.IsNullOrEmpty(parsed.commandId))
                        parsed.commandId = node.id + ":" + commandIndex;
                    script.commands.Add(parsed);
                }
            }

            AppendNodeTransitions(script, node);
            if (!HasExplicitDefaultTransition(node))
            {
                string fallbackNodeId = GetDefaultFlowTarget(node, sequenceNodes);
                AppendNodeFlowFallback(script, node, fallbackNodeId);
            }
        }

        return script;
    }

    public StoryActorDocument GetActor(string actorId)
    {
        if (string.IsNullOrEmpty(actorId) || actors == null)
            return null;

        return actors.FirstOrDefault(x => x != null && x.id == actorId);
    }

    public StorySceneResourceDocument GetSceneResource(string resourceId)
    {
        if (string.IsNullOrWhiteSpace(resourceId) || sceneResources == null)
            return null;

        return sceneResources.FirstOrDefault(value => value != null
            && string.Equals(value.id, resourceId, StringComparison.OrdinalIgnoreCase));
    }

    private List<StoryNodeDocument> GetOrderedNodes()
    {
        StoryNodeDocument[] allNodes = nodes ?? Array.Empty<StoryNodeDocument>();
        List<StoryNodeDocument> orderedNodes = allNodes
            .Where(node => node != null && !node.isBranch)
            .ToList();
        StoryNodeDocument entryNode = orderedNodes.FirstOrDefault(node => node.id == entry);
        if (entryNode != null)
        {
            orderedNodes.Remove(entryNode);
            orderedNodes.Insert(0, entryNode);
        }

        orderedNodes.AddRange(allNodes.Where(node => node != null && node.isBranch));
        return orderedNodes;
    }

    private static void AppendNodeTransitions(StoryScript script, StoryNodeDocument node)
    {
        StoryNodeTransitionDocument[] transitions = node.transitions ?? Array.Empty<StoryNodeTransitionDocument>();
        foreach (StoryNodeTransitionDocument transition in transitions
                     .Where(value => value != null && !value.isDefault)
                     .Concat(transitions.Where(value => value != null && value.isDefault)))
        {
            if (!transition.isEnd && string.IsNullOrWhiteSpace(transition.targetNodeId))
                continue;

            // 条件分支不允许以空条件组退化为无条件跳转。
            if (!transition.isDefault && (transition.condition == null || !transition.condition.hasConditions))
                continue;

            script.commands.Add(new StoryCommand
            {
                commandId = node.id + ":transition:" + (transition.transitionId ?? transition.targetNodeId),
                pointId = node.id,
                type = transition.isEnd ? StoryCommandType.End : StoryCommandType.Jump,
                args = transition.isEnd ? null : transition.targetNodeId,
                condition = transition.isDefault ? null : transition.condition,
            });
        }
    }

    private static bool HasExplicitDefaultTransition(StoryNodeDocument node)
    {
        return (node?.transitions ?? Array.Empty<StoryNodeTransitionDocument>())
            .Any(transition => transition != null
                && transition.isDefault
                && (transition.isEnd || !string.IsNullOrWhiteSpace(transition.targetNodeId)));
    }

    private static string GetDefaultFlowTarget(StoryNodeDocument node, List<StoryNodeDocument> sequenceNodes)
    {
        if (node == null)
            return string.Empty;

        if (node.isBranch)
            return node.fallbackNodeId;

        int nodeIndex = sequenceNodes.IndexOf(node);
        if (nodeIndex < 0 || nodeIndex + 1 >= sequenceNodes.Count)
            return string.Empty;

        return sequenceNodes[nodeIndex + 1]?.id;
    }

    private static void AppendNodeFlowFallback(StoryScript script, StoryNodeDocument node, string fallbackNodeId)
    {
        if (script == null || node == null)
            return;

        if (!string.IsNullOrWhiteSpace(fallbackNodeId))
        {
            script.commands.Add(new StoryCommand
            {
                commandId = node.id + ":flow",
                pointId = node.id,
                type = StoryCommandType.Jump,
                args = fallbackNodeId,
            });
            return;
        }

        script.commands.Add(new StoryCommand
        {
            commandId = node.id + ":flow:end",
            pointId = node.id,
            type = StoryCommandType.End,
        });
    }
}

